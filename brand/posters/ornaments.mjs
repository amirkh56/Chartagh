// Exports the site's Persian ornament library for posters: `node brand/posters/ornaments.mjs`
// → ornaments.css (pattern masks, colored with background-color) + shamseh.svg + toranj.svg
import { writeFileSync } from 'node:fs';
import { PATTERNS, starStr, lobedPath, PETAL } from '../../lib/patterns.js';

const out = new URL('.', import.meta.url);
const css = Object.entries(PATTERNS)
  .map(([k, { url, size }]) => `.p-${k} { -webkit-mask: ${url} 0 0 / ${size} repeat; mask: ${url} 0 0 / ${size} repeat; }`)
  .join('\n');
writeFileSync(new URL('ornaments.css', out), `/* generated by ornaments.mjs */\n${css}\n`);

const svg = (body) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 200">${body}</svg>`;
// شمسه: 16-point sun over an 8-point star
writeFileSync(new URL('shamseh.svg', out), svg(
  `<polygon points="${starStr(100, 100, 98, 16)}" fill="#E2492D"/><polygon points="${starStr(100, 100, 70, 8, Math.PI / 8)}" fill="#F8DDD3"/>` +
  `<polygon points="${starStr(100, 100, 46, 8)}" fill="#7E2414"/><circle cx="100" cy="100" r="14" fill="#D9C5A0"/>`));
// ترنج: scalloped medallion, petals, star core
const petals = Array.from({ length: 12 }, (_, i) => `<path d="${PETAL}" transform="translate(100 100) rotate(${i * 30}) translate(0 -34) scale(2.2)" fill="#C0704C"/>`).join('');
writeFileSync(new URL('toranj.svg', out), svg(
  `<path d="${lobedPath(100, 100, 92, 24)}" fill="#7E2414"/><path d="${lobedPath(100, 100, 80, 24)}" fill="#F8DDD3"/>` +
  `<path d="${lobedPath(100, 100, 70, 16)}" fill="#24130E"/>${petals}<polygon points="${starStr(100, 100, 26, 8)}" fill="#E2492D"/>`));
